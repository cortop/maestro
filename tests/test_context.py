def test_dossier_regenerated_by_ops_append_with_all_sections(cfg):
    home = cfg.home
    _create(cfg, "T-9", title="Dep ticket")
    ops.set_phase(cfg, "T-9", Phase.DONE, reason="done for the test")

    _create(cfg, "T-1", title="Widget", acs=("build the widget",), deps=("T-9",))

    ops.ask(cfg, "T-1", "Pick up T-1 — OK?", qid="q1")
    event_log.append(home, "T-1", "QuestionAnswered", {"qid": "q1", "answer": "ok"}, actor="human")
    ops.set_phase(cfg, "T-1", Phase.READY, reason="approved: ok")
    ops.set_phase(cfg, "T-1", Phase.IMPLEMENTING, reason="worktree ready")
    ops.fail(cfg, "T-1", "pytest red: test_widget failed")
    # CiObserved / ImplStepRecorded are appended raw (as the skill does via
    # `maestro append`), bypassing ops._append — the dossier still picks them
    # up on the next ops call because the fold reads the whole log fresh.
    event_log.append(home, "T-1", "CiObserved", {"state": "passing"}, actor="reconciler")
    event_log.append(home, "T-1", "ImplStepRecorded",
                     {"turn": 1, "role": "Implementer", "kind": "edit", "tool": "Edit",
                      "summary": "maestro/widget.py"}, actor="reconciler")
    ops.set_phase(cfg, "T-1", Phase.AWAITING_CI, reason="tests green")

    path = context.context_path(home, "T-1")
    assert path.exists()
    text = path.read_text(encoding="utf-8")

    assert "GENERATED by maestro" in text
    assert "# Context: T-1 — Widget" in text
    # Phase history: verbatim reasons
    assert "approved: ok" in text
    assert "worktree ready" in text
    assert "tests green" in text
    # Answered questions: verbatim Q + A
    assert "Pick up T-1 — OK?" in text
    assert "ok" in text
    # Failures
    assert "pytest red: test_widget failed" in text
    # CI observations
    assert "passing" in text
    # Impl steps
    assert "maestro/widget.py" in text
    # Dependencies + their phase
    assert "T-9: done" in text


def test_dossier_reflects_missing_dependency_gracefully(cfg):
    """A dependsOn key with no ticket yet still renders (default snapshot phase)."""
    _create(cfg, "T-1", deps=("T-404",))
    ops.observe_spec(cfg, "T-1")

    text = context.context_path(cfg.home, "T-1").read_text(encoding="utf-8")
    assert "T-404: triaging" in text


