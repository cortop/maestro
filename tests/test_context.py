def test_dossier_caps_phase_history_and_notes_the_omission(cfg):
    _create(cfg, "T-1")
    # Ping-pong past the cap so there are more phase changes than MAX_PHASE_CHANGES.
    total = context.MAX_PHASE_CHANGES + 5
    for i in range(total):
        dst = Phase.IMPLEMENTING if i % 2 == 0 else Phase.AWAITING_CI
        ops.set_phase(cfg, "T-1", dst, reason=f"iteration {i}")

    text = context.context_path(cfg.home, "T-1").read_text(encoding="utf-8")
    assert "earlier phase change(s) omitted" in text
    assert "iteration 0" not in text  # oldest dropped
    assert f"iteration {total - 1}" in text  # newest kept


