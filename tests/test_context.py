def test_render_is_byte_identical_for_the_same_events(cfg):
    _create(cfg, "T-1", acs=("do the thing",))
    ops.ask(cfg, "T-1", "OK?", qid="q1")
    event_log.append(cfg.home, "T-1", "QuestionAnswered", {"qid": "q1", "answer": "yes"}, actor="human")
    ops.set_phase(cfg, "T-1", Phase.READY, reason="approved: yes")

    events = event_log.read(cfg.home, "T-1")
    first = context.render("T-1", "Test ticket", events, {"T-9": "done"})
    second = context.render("T-1", "Test ticket", events, {"T-9": "done"})

    assert first == second


def test_render_output_is_stable_across_regenerate_calls(cfg):
    _create(cfg, "T-1")
    ops.set_phase(cfg, "T-1", Phase.READY, reason="approved: ok")

    path = context.context_path(cfg.home, "T-1")
    first = path.read_text(encoding="utf-8")
    context.regenerate(cfg.home, "T-1")  # no new events since
    second = path.read_text(encoding="utf-8")

    assert first == second


