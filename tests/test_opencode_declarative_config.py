def test_doctor_warns_missing_opencode_permission_config_then_ok_once_installed(home):
    _write_config(home, f'[maestro]\nrepo_path = "{home / "repo"}"\nrunner = "opencode"\n'
                        'runner_enabled = ["claude", "opencode"]\nmin_spawn_interval = 0\n')
    (home / "repo").mkdir()
    _seed(home, "T-1", phase=Phase.IMPLEMENTING, runner="opencode", runner_model="a:1b")

    code, report = _doctor(home)
    assert code == 0
    check = next(c for c in report["checks"] if c["name"] == "reconciler_permissions")
    assert check["status"] == "warn"
    assert "default" in check["missing_by_repo"]
    assert check["not_applicable_by_repo"] == {}

    assert cli_main(["--home", str(home), "install-commands", "--repo", "default"]) == 0

    code, report = _doctor(home)
    assert code == 0
    check = next(c for c in report["checks"] if c["name"] == "reconciler_permissions")
    assert check["status"] == "ok"
    assert check["missing_by_repo"] == {}


def test_doctor_warns_when_installed_config_is_stale(home):
    """A config.toml edit since the last install-commands run (e.g. a new
    [runner.opencode] table) must re-warn, not read a byte-stale file as ok --
    QW-1's rule: 'close but not exactly what would be generated now' warns."""
    repo = home / "repo"
    repo.mkdir()
    _write_config(home, f'[maestro]\nrepo_path = "{repo}"\nrunner = "opencode"\n'
                        'runner_enabled = ["claude", "opencode"]\nmin_spawn_interval = 0\n')
    _seed(home, "T-1", phase=Phase.IMPLEMENTING, runner="opencode", runner_model="a:1b")
    assert cli_main(["--home", str(home), "install-commands", "--repo", "default"]) == 0

    # Simulate drift: hand-edit the installed file after the fact.
    config_path = repo / ".opencode" / "opencode.jsonc"
    stale = json.loads(config_path.read_text())
    stale["permission"]["bash"]["maestro snapshot *"] = "ask"
    config_path.write_text(json.dumps(stale, indent=2) + "\n")

    code, report = _doctor(home)
    assert code == 0
    check = next(c for c in report["checks"] if c["name"] == "reconciler_permissions")
    assert check["status"] == "warn"


