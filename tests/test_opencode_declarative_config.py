def test_permission_block_allows_maestro_verbs_derived_from_one_definition(home):
    perms = runner_permissions.opencode_permission_block(home)
    assert perms["bash"]["maestro snapshot *"] == "allow"
    assert perms["bash"]["maestro env"] == "allow"
    # sourced from dispatcher.AGENT_TOOL_VERBS -- never a second hand-typed list
    for verb in disp.AGENT_TOOL_VERBS:
        assert perms["bash"][f"maestro {verb} *"] == "allow"
    # the destructive-command guard's own deny/ask entries are still present --
    # a real caller of opencode_bash_permissions, not a replacement for it
    assert any(action == "deny" for action in perms["bash"].values())


def test_permission_block_never_admits_a_blanket_allow(home):
    perms = runner_permissions.opencode_permission_block(home)
    assert perms["bash"].get("*") != "allow"
    assert "*" not in perms["external_directory"]
    for pattern in perms["external_directory"]:
        assert pattern != "*"
        assert str(home.resolve()) in pattern  # scoped under MAESTRO_HOME, never home-agnostic


def test_permission_block_external_directory_admits_a_real_spec_read(home):
    """Reproduces the exact glob shape a live opencode run requested for a Read
    tool call outside its own --dir (verified manually for this ticket, spec
    Notes) -- ``<containing-dir>/*`` -- against a real fnmatch matcher."""
    perms = runner_permissions.opencode_permission_block(home)
    spec_dir = (home / "tickets" / "T-64").resolve()
    requested_pattern = f"{spec_dir}/*"
    assert any(fnmatch.fnmatch(requested_pattern, allowed)
               for allowed, action in perms["external_directory"].items() if action == "allow")
    # inbox and derived (snapshots/context) are covered the same way
    for sub in ("inbox", "derived"):
        requested = f"{(home / sub).resolve()}/*"
        assert any(fnmatch.fnmatch(requested, allowed)
                   for allowed, action in perms["external_directory"].items() if action == "allow")


def test_permission_block_external_directory_does_not_admit_an_unrelated_path(home):
    perms = runner_permissions.opencode_permission_block(home)
    outside = "/etc/passwd"
    assert not any(fnmatch.fnmatch(outside, p) for p in perms["external_directory"])


