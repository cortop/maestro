def test_install_repo_writes_opencode_config_and_agent_stubs(home, tmp_path):
    repo = tmp_path / "acme"
    _write_config(home, f'[repos.acme]\npath = "{repo}"\n')

    assert cli_main(["--home", str(home), "install-commands", "--repo", "acme"]) == 0

    config_path = repo / ".opencode" / "opencode.jsonc"
    assert config_path.exists()
    written = json.loads(config_path.read_text())
    assert written["permission"] == runner_permissions.opencode_permission_block(home)
    assert written["$schema"] == "https://opencode.ai/config.json"

    agent_dir = repo / ".opencode" / "agent"
    installed = sorted(p.name for p in agent_dir.iterdir())
    assert installed == sorted(skills_install.PAYLOAD_NAMES)
    one = (agent_dir / "maestro-reconcile-implementing.md").read_text()
    assert "mode: primary" in one
    assert "description:" in one


def test_install_repo_opencode_config_and_agents_idempotent(home, tmp_path):
    repo = tmp_path / "acme"
    _write_config(home, f'[repos.acme]\npath = "{repo}"\n')

    assert cli_main(["--home", str(home), "install-commands", "--repo", "acme"]) == 0
    config_path = repo / ".opencode" / "opencode.jsonc"
    agent_dir = repo / ".opencode" / "agent"
    before_cfg = (config_path.read_text(), config_path.stat().st_mtime)
    before_agents = {p.name: (p.read_text(), p.stat().st_mtime) for p in agent_dir.iterdir()}

    assert cli_main(["--home", str(home), "install-commands", "--repo", "acme"]) == 0
    after_cfg = (config_path.read_text(), config_path.stat().st_mtime)
    after_agents = {p.name: (p.read_text(), p.stat().st_mtime) for p in agent_dir.iterdir()}
    assert before_cfg == after_cfg
    assert before_agents == after_agents
    assert [p for p in agent_dir.iterdir() if p.is_dir()] == []


def test_install_user_writes_opencode_config_and_agent_stubs(home, tmp_path, monkeypatch):
    user_dir = tmp_path / "user-commands"
    opencode_user_dir = tmp_path / "opencode-user-commands"
    monkeypatch.setenv("MAESTRO_USER_COMMANDS_DIR", str(user_dir))
    monkeypatch.setenv("MAESTRO_OPENCODE_COMMANDS_DIR", str(opencode_user_dir))

    assert cli_main(["--home", str(home), "install-commands", "--user"]) == 0

    config_path = opencode_user_dir.parent / "opencode.jsonc"
    assert config_path.exists()
    written = json.loads(config_path.read_text())
    assert written["permission"] == runner_permissions.opencode_permission_block(home)

    agent_dir = opencode_user_dir.parent / "agent"
    assert sorted(p.name for p in agent_dir.iterdir()) == sorted(skills_install.PAYLOAD_NAMES)


