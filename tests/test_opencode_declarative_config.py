def test_config_load_rejects_unrecognized_and_accepts_new_opencode_keys(home):
    from maestro import config as config_mod, store as store_mod
    (home / "config.toml").write_text('[runner.opencode]\nmodels = ["a:1b"]\nhost = "x:1"\n')
    cfg = config_mod.load(str(home))
    assert cfg.provider_config["runner"]["opencode"]["models"] == ["a:1b"]

    (home / "config.toml").write_text('[runner.opencode]\nmodel = ["typo"]\n')
    try:
        config_mod.load(str(home))
        raise AssertionError("expected a MaestroError for the unrecognized key")
    except store_mod.MaestroError as e:
        assert "model" in str(e)


