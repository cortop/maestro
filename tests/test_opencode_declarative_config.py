"""T-64/OC-6: the opencode declarative config write path -- both pieces
``sessions.py:341-347`` left waiting (``--agent <name>``'s file,
``runner_permissions.opencode_bash_permissions``'s only real caller) plus the
local ``ollama`` provider block ``OpencodeCliSessions`` needs to resolve its
model. All three are generated by ``maestro install-commands`` (both
``--repo`` and ``--user``, GA-15's existing verb) into ``opencode.jsonc`` +
``.opencode/agent/*.md``, one source, idempotent, never a blanket allow.

The ``external_directory`` fix (a reconcile skill's Read tool call for
``<MAESTRO_HOME>/tickets/<KEY>/spec.md`` -- outside opencode's own ``--dir``
worktree -- was denied: "The user rejected permission...") was verified for
real against a live ``opencode run`` + a real ``qwen3-coder:30b`` tool call
during this ticket's implementation (not reproduced here as an automated test
-- no ollama daemon/opencode binary is assumed present in CI, matching how
``test_e2e_opencode.py``/``test_runner_opencode_config.py`` already stub the
opencode executable rather than depend on a real one). What IS reproduced here
is the exact glob shape that live run confirmed opencode requests
(``<dir>/*``) via Python's own ``fnmatch`` -- a real matcher, not a hand-rolled
mock -- as a portable regression guard.
"""
